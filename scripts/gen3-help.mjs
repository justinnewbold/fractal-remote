#!/usr/bin/env node
/**
 * WHAT EACH KNOB DOES, FOR THE PHONE TO SAY OVER BLUETOOTH: the "?" under a
 * knob in Edit. Through the computer it is ForgeFX's answer to
 * GET /help/blocks/<slug> (server/src/help.ts, the codec's curated help for
 * an FM3, FM9 and Axe-Fx III, keyed by the unit's own setting numbers). Over
 * Bluetooth or a unit's USB cable nothing answered it, so the "?" was not
 * there. This writes the same answers for the phone to carry:
 * mobile/src/lib/gen3-help.js.
 *
 * NOTHING HERE IS RE-DERIVED: ForgeFX's own help.ts and devices.ts are
 * bundled as they are and RUN (its helpIndex for each unit's profile), as
 * scripts/gen3-tools.mjs does for the other tables. From the engine and the
 * codec the computer app carries, by the pins in desktop/forgefx.lock.json,
 * which are written into the file, where a test holds them to the lock. A NEW
 * PIN OF EITHER MEANS RUNNING THIS.
 *
 * An AM4 has no such help in the engine either, so it has none here.
 *
 *   node scripts/gen3-help.mjs <forgefx checkout> <forgefx-midi checkout, built>
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const target = join(root, 'mobile', 'src', 'lib', 'gen3-help.js')
const UNITS = [
  ['fm3', 0x11],
  ['fm9', 0x12],
  ['axefx3', 0x10]
]
const head = (dir) => execFileSync('git', ['rev-parse', 'HEAD'], { cwd: dir, encoding: 'utf8' }).trim()

export async function build(engine, codec) {
  const lock = JSON.parse(readFileSync(join(root, 'desktop', 'forgefx.lock.json'), 'utf8'))
  const pins = { forgefx: lock.forgefx.commit, codec: lock['forgefx-midi'].commit }
  if (head(engine) !== pins.forgefx) throw new Error(`ForgeFX at ${engine} is on ${head(engine)}, not the pinned ${pins.forgefx} (desktop/forgefx.lock.json).`)
  if (head(codec) !== pins.codec) throw new Error(`The codec at ${codec} is on ${head(codec)}, not the pinned ${pins.codec} (desktop/forgefx.lock.json).`)
  const work = mkdtempSync(join(tmpdir(), 'gen3-help-'))
  try {
    mkdirSync(join(work, 'node_modules'), { recursive: true })
    symlinkSync(resolve(codec), join(work, 'node_modules', 'forgefx-midi'))
    const entry = join(work, 'entry.ts')
    const src = join(resolve(engine), 'server', 'src')
    writeFileSync(entry, [`export { PROFILES } from ${JSON.stringify(join(src, 'devices.ts'))}`, `export { helpIndex } from ${JSON.stringify(join(src, 'help.ts'))}`].join('\n'))
    const out = join(work, 'bundle.mjs')
    execFileSync(join(root, 'node_modules', '.bin', 'esbuild'), [entry, '--bundle', '--format=esm', '--platform=node', `--outfile=${out}`, '--log-level=error'], {
      env: { ...process.env, NODE_PATH: join(work, 'node_modules') },
      stdio: 'inherit'
    })
    const f = await import(pathToFileURL(out).href)
    /* Every distinct piece of help once; a unit names its own by their place. */
    const texts = []
    const at = new Map()
    const textAt = (h) => {
      const one = h.tip ? { blurb: h.blurb, tip: h.tip } : { blurb: h.blurb }
      const key = JSON.stringify(one)
      if (!at.has(key)) at.set(key, texts.push(one) - 1)
      return at.get(key)
    }
    const units = {}
    for (const [unit, model] of UNITS) {
      const profile = f.PROFILES[model]
      if (!profile || profile.model !== model) throw new Error(`ForgeFX has no profile for ${unit}.`)
      const blocks = {}
      for (const [slug, dto] of Object.entries(f.helpIndex(profile).blocks)) {
        const params = {}
        for (const [id, h] of Object.entries(dto.params)) if (h && typeof h.blurb === 'string' && h.blurb) params[id] = textAt(h)
        if (Object.keys(params).length) blocks[slug] = params
      }
      units[unit] = blocks
    }
    return { pins, texts, units }
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
}

export function render({ pins, texts, units }) {
  return [
    '/*',
    ' * GENERATED by scripts/gen3-help.mjs from ForgeFX and its codec at the',
    ' * commits the computer app carries. Do not edit: run the script.',
    ' *',
    ' * What each knob does, as the computer app answers GET /help/blocks/<slug>',
    ' * for an FM3, FM9 and Axe-Fx III, for the phone to answer over Bluetooth.',
    ' */',
    `export const GEN3_HELP_FROM = ${JSON.stringify(pins)}`,
    '',
    '/** Every distinct piece of help, once: { blurb, tip? }. */',
    'export const HELP_TEXTS = [',
    ...texts.map((t, i) => `  ${JSON.stringify(t)}${i < texts.length - 1 ? ',' : ''}`),
    ']',
    '',
    '/** Each unit: a block’s slug to { setting number: place in HELP_TEXTS }. */',
    'export const GEN3_HELP = {',
    ...Object.entries(units).map(([unit, u], i, all) => `  ${unit}: ${JSON.stringify(u)}${i < all.length - 1 ? ',' : ''}`),
    '}',
    '',
    '/** The computer’s own answer for one block on one unit, { params: { [setting]: { blurb, tip? } } }, or null where it has none. */',
    'export const gen3BlockHelp = (unit, slug) => {',
    '  const block = GEN3_HELP[unit]?.[String(slug || \'\').toLowerCase()]',
    '  if (!block) return null',
    '  const params = {}',
    '  for (const [id, i] of Object.entries(block)) params[id] = { ...HELP_TEXTS[i] }',
    '  return { slug: String(slug).toLowerCase(), params }',
    '}',
    ''
  ].join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [engine, codec] = process.argv.slice(2)
  if (!engine || !codec) {
    console.error('usage: node scripts/gen3-help.mjs <forgefx checkout> <forgefx-midi checkout, built>')
    process.exit(2)
  }
  const made = render(await build(engine, codec))
  writeFileSync(target, made)
  console.log(`wrote ${target} (${made.length} bytes)`)
}
