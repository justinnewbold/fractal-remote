/**
 * The picture the watch draws, from the phone's store and the few things the
 * stage screen works out (the label of the slot, where Previous and Next would
 * land, each pedal's colour and short name).
 *
 * Every field is always present, so the watch never has to wonder whether a
 * missing one means "none" or "unknown".
 */
export function watchState({
  preset = null,
  label = '',
  scene = null,
  sceneNames = [],
  sceneCount = 0,
  pedals = [],
  tunerOn = false,
  tuning = null,
  linked = false,
  canPrevious = false,
  canNext = false,
  metronome = null,
  /* The order of the watch's pages and which are hidden, for a watch that has said it does this; no order (null) for any other, and then neither field is sent at all. */
  pages = null,
  hidden = null,
  /* The Tempo page's picture, for a watch that has said it has one; none (null) for any other, and then the field is not sent at all. */
  tempo = null,
  /* Whether the watch leaves the tuner on when its page is left, for a watch that has said it knows how; none (null) for any other, and then the field is not sent at all. */
  tunerStays = null,
  /* Whether a held pedal offers quick edit, and the open sheet's knobs (QUICK EDIT ON THE WRIST), for a watch that has said it knows how; none (null) for any other, and then neither field is sent at all. */
  quickEdit = null,
  quick = null,
  at = Date.now()
} = {}) {
  const count = int(sceneCount) && sceneCount > 0 ? Math.min(sceneCount, 8) : 0
  const note = tunerOn && tuning && typeof tuning.note === 'string' && tuning.note ? tuning.note.slice(0, 3) : ''
  const cents = note && Number.isFinite(tuning.cents) ? Math.max(-50, Math.min(50, Math.round(tuning.cents))) : 0
  /* The open sheet's knobs, only where quick edit is offered and only for a pedal this picture shows. */
  const open = quickEdit === true ? quickForWatch(quick, (Array.isArray(pedals) ? pedals : []).filter((p) => p && int(p.id)).slice(0, WATCH_PEDALS_MAX)) : null
  return {
    v: WATCH_LINK_VERSION,
    at,
    linked: !!linked,
    preset: {
      number: int(preset?.number) ? preset.number : -1,
      label: text(label, 8),
      name: text(preset?.name, 32)
    },
    canPrevious: !!canPrevious,
    canNext: !!canNext,
    scene: int(scene) && scene >= 0 && scene < count ? scene : -1,
    scenes: Array.from({ length: count }, (_, i) => text(sceneNames?.[i], 16) || `Scene ${i + 1}`),
    pedals: (Array.isArray(pedals) ? pedals : [])
      .filter((p) => p && int(p.id))
      .slice(0, WATCH_PEDALS_MAX)
      .map((p) => ({
        id: p.id,
        short: text(p.short, 5) || text(p.name, 5),
        name: text(p.name, 24),
        on: p.on === true,
        fill: /^#[0-9a-f]{6}$/i.test(p.fill || '') ? p.fill : '#7d8591',
        ink: /^#[0-9a-f]{6}$/i.test(p.ink || '') ? p.ink : '#ffffff',
        /* The letter in the tile's corner, as on the phone; '' when the unit
           has not said. */
        channel: letter(p.channel),
        /* What a hold may switch it to; [] and a hold does nothing. A watch
           older than this reads neither field, and is none the worse: the
           link's version stays 1, because nothing it knows changed meaning. */
        channels: channelChoices(p.channels),
        /* The word under its name, as Play's tile says it: on an AM4's amp,
           Boost on, Boost off or Amp off (shared/am4-boost.mjs boostPedals
           puts it there, by Play's own boostWord); '' for every other pedal,
           and for a boost the unit has not said. Passed on as it came, never
           worked out here. A watch from before the build that draws it reads
           no such field and shows the pedal lit or dark as it did, so the
           version stays 1 for this too. */
        word: text(p.word, 12)
      })),
    tuner: {
      on: !!tunerOn,
      note,
      octave: note && int(tuning?.octave) ? tuning.octave : -1,
      cents,
      inTune: !!note && Math.abs(cents) <= WATCH_IN_TUNE_CENTS
    },
    /* Tap on every beat, at this tempo — or not. See shared/metronome.mjs. */
    metronome: metronomeForWatch(metronome),
    /* The Tempo page (tempoForWatch, above), only where the caller gives
       one, which is only to a watch that has said it has that page. */
    ...(tempo === null || tempo === undefined ? null : { tempo: tempoForWatch(tempo) }),
    /* The iPhone's "stays on when you swipe away" switch (THE TUNER, AND
       LEAVING ITS PAGE), true only when it is on; sent only where the
       caller says, which is only to a watch that knows what to do with it. */
    ...(tunerStays === null || tunerStays === undefined ? null : { tunerStays: tunerStays === true }),
    /* The pages in the order chosen on the iPhone, always every one
       (watchPageOrder), and those of them not to draw, never every one
       (watchPagesHidden). Sent only where the caller says an order, which
       is only to a watch that has said it does this: to any other the
       picture is exactly what it was, field for field, and the version
       stays 1, because nothing a watch already reads changed meaning. */
    ...(pages === null || pages === undefined ? null : { pages: watchPageOrder(pages), hidden: watchPagesHidden(hidden) }),
    /* Quick edit (QUICK EDIT ON THE WRIST): whether a hold offers it, true
       only for a plain true, and the open sheet's knobs once they are read.
       Sent only where the caller says, which is only to a watch that has
       said it knows `quick`: to any other the picture has neither field. */
    ...(quickEdit === null || quickEdit === undefined ? null : { quickEdit: quickEdit === true, ...(open ? { quick: open } : null) })
  }
}

/** The metronome's word to the watch: on only with a tempo anybody would play to. */
function metronomeForWatch(m) {
  const bpm = Number(m?.bpm)
  const on = m?.on === true && Number.isFinite(bpm) && bpm >= 20 && bpm <= 400
  return { on, bpm: on ? Math.round(bpm * 10) / 10 : 0 }
}

/**
 * A message from the watch, as one of the eleven things it may ask, or null.
 *
 *   { do: 'scene', index }      — switch to that scene (0-based)
 *   { do: 'pedal', id, on }     — that block on or off
 *   { do: 'channel', id, channel } — that block onto that channel, a letter ('B')
 *   { do: 'preset', step }      — Previous (-1) or Next (+1), as the stage screen steps
 *   { do: 'tuner', on }         — the tuner page opened or closed
 *   { do: 'hello' }             — the watch app opened: send the picture now
 *                                 (with `knows`, from a watch that says what it
 *                                 knows: see WATCH_KNOWS)
 *   { do: 'tap' }               — one tap of Play's Tap button (THE TEMPO PAGE)
 *   { do: 'wrist', on }         — the metronome's tap on the wrist, on or off
 *   { do: 'here' }              — the watch is on screen: nothing to do but
 *                                 stay awake (THE CHECK-IN)
 *   { do: 'knobs', id }         — a held pedal's sheet opened: read its knobs;
 *                                 id null when it closes (QUICK EDIT ON THE WRIST)
 *   { do: 'knob', id, key, at } — that knob of that pedal to that place in its
 *                                 range, 0 to 1
 *
 * `state` is the last picture sent, so a scene or a pedal the watch could not
 * have been shown is refused rather than sent to the unit — and so is a
 * channel that pedal was not offered in it, which is every channel while the
 * Play screen's own hold would do nothing.
 */
export function watchCommand(msg, state) {
  if (!msg || typeof msg !== 'object') return null
  switch (msg.do) {
    /* The check-in: one word, with nothing in it to carry and nothing to check it against. */
    case 'here':
      return { do: 'here' }
    case 'hello':
      /* A watch from before `knows` says none, and its hello is the one word it always was. */
      return Array.isArray(msg.knows) ? { do: 'hello', knows: watchKnows(msg.knows) } : { do: 'hello' }
    case 'scene': {
      const count = Array.isArray(state?.scenes) ? state.scenes.length : 0
      return int(msg.index) && msg.index >= 0 && msg.index < count ? { do: 'scene', index: msg.index } : null
    }
    case 'pedal': {
      const shown = (state?.pedals || []).some((p) => p.id === msg.id)
      return int(msg.id) && shown && typeof msg.on === 'boolean' ? { do: 'pedal', id: msg.id, on: msg.on } : null
    }
    case 'channel': {
      const pedal = int(msg.id) ? (state?.pedals || []).find((p) => p.id === msg.id) : null
      const offered = Array.isArray(pedal?.channels) ? pedal.channels : []
      return pedal && typeof msg.channel === 'string' && offered.includes(msg.channel)
        ? { do: 'channel', id: msg.id, channel: msg.channel }
        : null
    }
    case 'preset':
      return msg.step === 1 || msg.step === -1 ? { do: 'preset', step: msg.step } : null
    case 'tuner':
      return typeof msg.on === 'boolean' ? { do: 'tuner', on: msg.on } : null
    /* The Tempo page's two (THE TEMPO PAGE, above): only from a watch the last picture gave that page to, and a tap only where it offered one. */
    case 'tap':
      return state?.tempo?.tap === true ? { do: 'tap' } : null
    case 'wrist':
      return state?.tempo && typeof state.tempo === 'object' && typeof msg.on === 'boolean' ? { do: 'wrist', on: msg.on } : null
    /* Quick edit's two (QUICK EDIT ON THE WRIST, above): only where the last picture offered it. The knobs of a pedal that picture showed and a hold opens (one with channels to choose), or of none, when the sheet closes. */
    case 'knobs': {
      if (state?.quickEdit !== true) return null
      if (msg.id === null) return { do: 'knobs', id: null }
      const pedal = int(msg.id) ? (state.pedals || []).find((p) => p.id === msg.id) : null
      return pedal && Array.isArray(pedal.channels) && pedal.channels.length > 1 ? { do: 'knobs', id: msg.id } : null
    }
    /* A turn: only a knob the last picture listed for that pedal, to a place inside its range. */
    case 'knob': {
      const open = state?.quickEdit === true && state.quick && typeof state.quick === 'object' ? state.quick : null
      const listed = open && int(msg.id) && msg.id === open.id && typeof msg.key === 'string' && Array.isArray(open.knobs) && open.knobs.some((k) => k.key === msg.key)
      return listed && num(msg.at) && msg.at >= 0 && msg.at <= 1 ? { do: 'knob', id: msg.id, key: msg.key, at: watchKnobAt(msg.at) } : null
    }
    default:
      return null
  }
}

/**
 * Whether two pictures differ in anything but the clock — so the phone does
 * not wake the watch's radio to say nothing has changed.
 */
export function sameWatchState(a, b) {
  if (!a || !b) return false
  const { at: _a, ...restA } = a
  const { at: _b, ...restB } = b
  return JSON.stringify(restA) === JSON.stringify(restB)
}

/**
 * WHEN TO SEND. The phone's store changes many times a second while somebody
 * plays — a tuner reading every 80 ms, a scene's states landing in two steps —
 * and every send wakes the watch's radio. So a picture goes straight away when
 * nothing has gone for a while, and otherwise once the gap is up: a tenth of a
 * second while only the tuner moved, a quarter for anything else. One that is
 * the same as the last is not sent at all.
 *
 * `send(state, { urgent })` is the native call; urgent is false for a picture
 * that only moved the tuner, so the native side can skip the slower, kept
 * copy (applicationContext) for those. `now`, `schedule` and `cancel` are the
 * clock, injected so the tests can turn it by hand.
 */
export function createWatchSender({ send, now = () => Date.now(), schedule = setTimeout, cancel = clearTimeout }) {
  let last = null
  let lastAt = -Infinity
  let pending = null
  let timer = null

  const tunerOnly = (a, b) => {
    if (!a || !b) return false
    return sameWatchState({ ...a, tuner: null }, { ...b, tuner: null })
  }

  const fire = () => {
    timer = null
    if (!pending) return
    const state = pending
    pending = null
    const urgent = !tunerOnly(last, state)
    last = state
    lastAt = now()
    try {
      send(state, { urgent })
    } catch {
      /* A watch that is not there is not a fault on the phone. */
    }
  }

  return {
    push(state) {
      if (sameWatchState(state, pending || last)) return
      pending = state
      const gap = tunerOnly(last, state) ? WATCH_TUNER_MS : WATCH_STATE_MS
      const wait = Math.max(0, lastAt + gap - now())
      if (wait === 0) {
        if (timer) cancel(timer)
        fire()
      } else if (!timer) {
        timer = schedule(fire, wait)
      }
    },
    /** Send the latest picture now — the watch has just opened and asked. */
    flush(state) {
      if (timer) cancel(timer)
      timer = null
      pending = state || pending || last
      if (pending) {
        last = null
        fire()
      }
    },
    stop() {
      if (timer) cancel(timer)
      timer = null
      pending = null
    }
  }
}
