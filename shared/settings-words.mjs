/**
 * THE PHONE & COMPUTER ROW'S LINE, which is also My rig's while it is shut:
 * how far along the chain gets, from this end to the unit.
 *
 * `link` is the link as the top bar shows it ('connected', 'joining',
 * 'no-answer', 'signed-out' or 'off'), `unitState` the unit's 'present',
 * 'missing', 'silent' or 'unknown' (the same four words the top bar's pill
 * reads), and `unit` the unit's short name. In the demo it names the unit
 * the demo is being, never a fixed one: an Axe-Fx III demo once called
 * itself an FM3 here.
 *
 * The phone's Bluetooth line is the phone's own, beside it in Settings.js: a
 * browser cannot reach a Bluetooth MIDI adapter. And the computer app's
 * window, which is the computer, keeps its own words about the phone remote.
 */
export function pairLine({ demo = false, demoName = '', link, unitState = 'unknown', unit = '' } = {}) {
  if (demo) return `Demo — simulated ${demoName || 'unit'}`
  if (link === 'joining') return 'Finding your computer'
  if (link === 'no-answer') return 'Your computer isn’t answering'
  if (link !== 'connected') return 'Not connected'
  if (unitState === 'missing') return 'Computer connected · no unit'
  if (unitState === 'silent') return `Computer connected · ${unit || 'unit'} not answering`
  return `${unit || 'Unit'} · connected`
}
